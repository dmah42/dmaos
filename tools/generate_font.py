def main():
    out_path = Path(sys.argv[1] if len(sys.argv) > 1 else "kernel/fonts/font8x16.bin")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    data = bytearray()
    for glyph in CP437_GLYPHS:
        data.extend(glyph)

    assert len(data) == 4096, f"Expected 4096 bytes, got {len(data)}"
    out_path.write_bytes(data)
    print(f"Generated {out_path} ({len(data)} bytes)")

if __name__ == "__main__":
    main()
